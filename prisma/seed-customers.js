async function main() {
  console.log('Seeding customers...');

  for (const c of customers) {
    try {
      await prisma.customer.upsert({
        where: { accountNumber: c.accountNumber },
        update: c,
        create: c,
      });
      console.log(`  ✓ ${c.accountNumber} — ${c.companyName}`);
    } catch (err) {
      // Try by email if accountNumber upsert fails
      try {
        await prisma.customer.upsert({
          where: { email: c.email },
          update: c,
          create: c,
        });
        console.log(`  ✓ ${c.accountNumber} — ${c.companyName} (by email)`);
      } catch (err2) {
        console.error(`  ✗ ${c.accountNumber} — ${c.companyName}:`, err2.message);
      }
    }
  }

  console.log('\nDone! Seeded', customers.length, 'customers.');
}

main()
  .catch(e => { console.error(e); process.exit(1); })
  .finally(() => prisma.$disconnect());
